CREATE TABLE IF NOT EXISTS matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    match_id VARCHAR(64) NOT NULL,
    game_mode VARCHAR(64) DEFAULT 'Unknown' NOT NULL,
    queue_id INTEGER,
    duration_seconds BIGINT DEFAULT 0 NOT NULL,
    game_end_at TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    platform VARCHAR(32),
    region VARCHAR(32),
    created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_matches PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS player_matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    player_id BIGINT NOT NULL,
    match_id BIGINT NOT NULL,
    puuid VARCHAR(128) NOT NULL,
    champion_id INTEGER,
    champion_name VARCHAR(64) DEFAULT 'Unknown' NOT NULL,
    result VARCHAR(16) DEFAULT 'UNKNOWN' NOT NULL,
    lane VARCHAR(32),
    role VARCHAR(32),
    kills INTEGER DEFAULT 0 NOT NULL,
    deaths INTEGER DEFAULT 0 NOT NULL,
    assists INTEGER DEFAULT 0 NOT NULL,
    creep_score INTEGER DEFAULT 0 NOT NULL,
    gold_earned INTEGER DEFAULT 0 NOT NULL,
    damage_dealt_to_champions INTEGER DEFAULT 0 NOT NULL,
    vision_score INTEGER DEFAULT 0 NOT NULL,
    notification_suppressed BOOLEAN DEFAULT FALSE NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_player_matches PRIMARY KEY (id),
    CONSTRAINT fk_player_matches_player FOREIGN KEY (player_id) REFERENCES players (id) ON DELETE CASCADE,
    CONSTRAINT fk_player_matches_match FOREIGN KEY (match_id) REFERENCES matches (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS notification_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tracked_match_id BIGINT NOT NULL,
    status VARCHAR(16) DEFAULT 'PENDING' NOT NULL,
    attempt_count INTEGER DEFAULT 0 NOT NULL,
    last_attempt_at TIMESTAMP(6) WITH TIME ZONE,
    next_attempt_at TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    last_error VARCHAR(500),
    telegram_message_id INTEGER,
    sent_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_notification_outbox PRIMARY KEY (id),
    CONSTRAINT fk_notification_outbox_tracked_match FOREIGN KEY (tracked_match_id) REFERENCES tracked_matches (id)
);

CREATE TABLE IF NOT EXISTS external_call_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    integration VARCHAR(24) NOT NULL,
    operation VARCHAR(64) NOT NULL,
    status VARCHAR(16) NOT NULL,
    category VARCHAR(32),
    summary VARCHAR(500),
    occurred_at TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_external_call_logs PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS poll_locks (
    name VARCHAR(64) NOT NULL,
    owner VARCHAR(128),
    locked_until TIMESTAMP(6) WITH TIME ZONE,
    acquired_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    version BIGINT,
    CONSTRAINT pk_poll_locks PRIMARY KEY (name)
);

CREATE TABLE IF NOT EXISTS poll_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    started_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP(6) WITH TIME ZONE,
    status VARCHAR(32) NOT NULL,
    owner VARCHAR(128),
    current_player VARCHAR(160),
    current_stage VARCHAR(120),
    rate_limit_paused_until TIMESTAMP(6) WITH TIME ZONE,
    rate_limit_message VARCHAR(500),
    players_processed INTEGER DEFAULT 0 NOT NULL,
    new_matches_found INTEGER DEFAULT 0 NOT NULL,
    notifications_sent INTEGER DEFAULT 0 NOT NULL,
    error_summary VARCHAR(500),
    CONSTRAINT pk_poll_runs PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS app_configuration (
    id BIGINT NOT NULL,
    riot_api_key VARCHAR(1200),
    riot_region VARCHAR(32) DEFAULT 'EUROPE' NOT NULL,
    telegram_bot_token VARCHAR(1200),
    telegram_chat_id VARCHAR(1200),
    polling_enabled BOOLEAN,
    polling_manual_only BOOLEAN,
    polling_fixed_delay VARCHAR(32),
    polling_match_window_size INTEGER,
    polling_pagination_limit INTEGER,
    created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
