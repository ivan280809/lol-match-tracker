CREATE TABLE IF NOT EXISTS players (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    game_name VARCHAR(64) NOT NULL,
    tag_line VARCHAR(32) NOT NULL,
    platform VARCHAR(16) DEFAULT 'EUW1' NOT NULL,
    puuid VARCHAR(128),
    active BOOLEAN DEFAULT TRUE NOT NULL,
    archived_at TIMESTAMP(6) WITH TIME ZONE,
    last_polled_at TIMESTAMP(6) WITH TIME ZONE,
    track_from TIMESTAMP(6) WITH TIME ZONE,
    backfill_mode VARCHAR(40) DEFAULT 'NONE' NOT NULL,
    last_successful_sync_at TIMESTAMP(6) WITH TIME ZONE,
    last_sync_status VARCHAR(32),
    last_error VARCHAR(500),
    rank_queue_type VARCHAR(32),
    rank_tier VARCHAR(24),
    rank_division VARCHAR(8),
    rank_league_points INTEGER,
    rank_score INTEGER,
    rank_updated_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_players PRIMARY KEY (id)
);

